func T(lang, key string) string {
	if l, ok := translations[lang]; ok {
		if val, ok := l[key]; ok {
			return val
		}
	}
	// Fallback to English if key not found in specified language
	if val, ok := translations["English"][key]; ok {
		return val
	}
	return key
}

func Tf(lang, key string, a ...interface{}) string {
	return fmt.Sprintf(T(lang, key), a...)
}
